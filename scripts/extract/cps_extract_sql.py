"""Generate duckdb SQL that turns the IPUMS CPS Computer and Internet Use Supplement samples (data/ipums/cps/<sample>.parquet)
into data/extracts/cps/cps_ci_<sample>.parquet, one file per supplement month. Writes build/sql/cps_internet_supplement.sql and
build/sql/run_cps.sh (which creates the output directory). See scripts/extract/README.md for the samples and variables.

Column resolution: household variables are read with or without the internal _H suffix (YEAR_H or YEAR, STATEFIP_H or STATEFIP,
...). Weights are written as DOUBLE on the person scale: the internal files carry WTFINL, HWTFINL, CISUPPWT and CIPWT as integers
with four implied decimals, so they are divided by 10,000; a standard extract delivers them with the decimals applied and is left
as is. The scale is detected from the weight column's type (integer = internal) and can be forced with --wt-scale.

Usage: uv run python scripts/extract/cps_extract_sql.py [--ipums-dir data/ipums/cps] [--wt-scale 10000|1]
"""
import argparse, pathlib, duckdb
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "build" / "sql"; OUT.mkdir(parents=True, exist_ok=True)
ap = argparse.ArgumentParser(); ap.add_argument("--ipums-dir", default="data/ipums/cps"); ap.add_argument("--wt-scale", type=float, default=None); args = ap.parse_args()
PQ = args.ipums_dir; DEST = "data/extracts/cps"
SAMPLES = ["cps2009_10s","cps2010_10s","cps2011_07s","cps2012_10s","cps2013_07s","cps2015_07s","cps2017_11s","cps2019_11s","cps2021_11s","cps2023_11s"]
HH = ["YEAR","MONTH","SERIAL","CPSID","MISH","STATEFIP","COUNTY","METFIPS","METAREA","METRO","CBSASZ","INDIVIDCC","FAMINC","HHTENURE","HWTFINL"]
PER = ["PERNUM","CPSIDP","AGE","SEX","RACE","HISPAN","WTFINL","CISUPPWT","CIPWT","CINETHH","CICONTYP","CIHHCOMP","CIUSECMP","CINUMCMP","CICOMPYR",
       "CIHSNET","CINONET","CINONTMO","CISTPNET","CINTOUTH","CINTLIBH","CINTOTHHH","CINTSCHH","CINTUSE","CINETHP","CINTOUT","CINTOTHH","CINTLIB","CINTSCH",
       "CIEMAIL","CIHFORWK","CINTJBSR","CINTPHON","CINTFUN","CIPRIV2"]
WEIGHTS = ["WTFINL","HWTFINL","CISUPPWT","CIPWT"]
REQUIRED = ["YEAR","SERIAL","PERNUM","AGE","SEX","STATEFIP","WTFINL","CISUPPWT"]
parts, runner, present = [], ["#!/bin/bash", "set -u", f"mkdir -p {DEST}"], []
for s in SAMPLES:
    f = ROOT / PQ / f"{s}.parquet"
    if not f.exists(): print("missing extract:", f); continue
    desc = {r[0]: r[1] for r in duckdb.sql(f"describe select * from read_parquet('{f}')").fetchall()}
    def src(c): return next((x for x in [c, c + "_H"] if x in desc), None)
    missing = [c for c in REQUIRED if src(c) is None]
    if missing: raise SystemExit(f"{s}: required columns not found: {missing}")
    wcol = src("WTFINL"); scale = args.wt_scale or (10000.0 if any(t in desc[wcol].upper() for t in ("INT", "BIGINT", "HUGEINT")) else 1.0)
    cols = []
    for c in HH + PER:
        x = src(c)
        if x is None: cols.append(f"NULL::{'DOUBLE' if c in WEIGHTS else 'INTEGER'} AS {c}")
        elif c in WEIGHTS: cols.append(f"{x}/{scale} AS {c}")
        else: cols.append(f"{x} AS {c}" if x != c else c)
    parts.append(f"COPY (SELECT '{s}' AS SAMPLE,\n  " + ",\n  ".join(cols) + f"\nFROM read_parquet('{PQ}/{s}.parquet') ORDER BY SERIAL, PERNUM) TO '{DEST}/cps_ci_{s}.parquet' (FORMAT PARQUET, COMPRESSION ZSTD);")
    present.append((s, scale))
sql = "-- generated by scripts/extract/cps_extract_sql.py; weights divided by the scale noted per sample\n" + "".join(f"-- {s}: weight scale {sc:g}\n" for s, sc in present) + "PRAGMA threads=8;\n" + "\n".join(parts) + "\n"
(OUT / "cps_internet_supplement.sql").write_text(sql)
runner.append("duckdb < build/sql/cps_internet_supplement.sql && echo ALLDONE || echo FAILED")
(OUT / "run_cps.sh").write_text("\n".join(runner) + "\n")
print("wrote build/sql/cps_internet_supplement.sql for", len(present), "samples")
